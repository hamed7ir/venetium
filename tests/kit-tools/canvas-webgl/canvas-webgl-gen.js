// Generates (or checks) kit/data/canvas-webgl-golden.js from kit/lib/canvas-webgl-model.js under Node. NOT part of the kit (the page
// never loads it; it is a server-side tool, kept outside the kit folder so that the kit holds only what the device runs):
//   F:\cr\src\third_party\node\win\node.exe venetium\tests\kit-tools\canvas-webgl\canvas-webgl-gen.js           writes kit/data/canvas-webgl-golden.js
//   F:\cr\src\third_party\node\win\node.exe venetium\tests\kit-tools\canvas-webgl\canvas-webgl-gen.js --check   writes nothing; exit 0 if the file on
//                                                                                                  disk equals what would be written, else 1
// The golden values are what the reference model (an independent software rasteriser, no canvas API) predicts for the scene.
'use strict';
const fs = require('fs'), path = require('path');
const KIT = path.resolve(__dirname, '..', '..', 'kit');
const CW = require(path.join(KIT, 'lib', 'canvas-webgl-model.js'));
const ops = CW.scene();
const px = CW.model(ops);
const kinds = {}; for (const o of ops) kinds[o.t] = (kinds[o.t] || 0) + 1;
let opaque = 0, clear = 0; for (let i = 3; i < px.length; i += 4) { if (px[i] === 255) opaque++; else if (px[i] === 0) clear++; }
const g = { w: CW.W, h: CW.H, seed: CW.SEED, ops: ops.length, kinds, opsCrc: CW.hex(CW.crcStr(JSON.stringify(ops))), crc: CW.hex(CW.crc32(px)), opaquePixels: opaque, transparentPixels: clear, bytes: px.length };
if (opaque + clear !== CW.W * CW.H) throw new Error('scene has pixels that are neither opaque nor transparent');
const out = '// Venetium test kit, page canvas-webgl: golden values of the exact 2D scene. GENERATED by kit-tools/canvas-webgl/canvas-webgl-gen.js (Node)\n' +
  '// from lib/canvas-webgl-model.js; do not edit by hand.\nwindow.CW_GOLDEN = ' + JSON.stringify(g, null, 1) + ';\n';
const target = path.join(KIT, 'data', 'canvas-webgl-golden.js');
if (process.argv.includes('--check')) {
  const have = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : null;
  const same = have === out;
  console.log((same ? 'OK: ' : 'DIFFERENT: ') + target + (same ? ' is byte for byte what the model generates' : ' is not what the model generates') + ' (crc ' + g.crc + ', ops crc ' + g.opsCrc + ')');
  process.exit(same ? 0 : 1);
}
fs.writeFileSync(target, out);
console.log(JSON.stringify(g));
